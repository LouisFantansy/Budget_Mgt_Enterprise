#!/bin/bash

################################################################################
# 企业级预算管理系统 - 快速重启脚本
# 使用方法：sudo ./restart.sh
################################################################################

set -e

echo "正在重启服务..."

cd /opt/Budget_Mgt_Enterprise

# 重启所有服务
docker-compose restart

# 等待服务启动
sleep 15

# 检查服务状态
docker-compose ps

echo "服务重启完成！"
